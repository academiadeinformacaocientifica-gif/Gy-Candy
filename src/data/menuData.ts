// Helper to format currency in Angolan standard (e.g., "6.000 Kz")
export function formatKwanza(amount: number): string {
  const formatted = amount.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.');
  return `${formatted} Kz`;
}
